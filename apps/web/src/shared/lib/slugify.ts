const MAX_SLUG_LENGTH = 48

// "Барбершоп Азамат" → "barbershop-azamat"; Kyrgyz letters included.
export const slugify = (value: string) =>
  value
    .toLowerCase()
    .split('')
    .map((char) => CYRILLIC_TO_LATIN[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_SLUG_LENGTH)
    .replace(/-+$/g, '')
